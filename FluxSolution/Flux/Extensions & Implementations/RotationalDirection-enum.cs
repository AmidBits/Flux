namespace Flux
{
  /// <summary>
  /// <para>Specifies the direction of rotational operations.</para>
  /// </summary>
  public enum RotationalDirection
  {
    /// <summary>
    /// <para>The order is clockwise, i.e. in the direction of the clock.</para>
    /// </summary>
    ClockWise,
    /// <summary>
    /// <para>The order is counter-clockwise, or anti-clockwise, i.e. in the opposite direction of the clock.</para>
    /// </summary>
    CounterClockWise
  }
}
