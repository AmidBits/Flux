namespace Flux
{
  /// <summary>
  /// <para>Specifies the sign of a number.</para>
  /// </summary>
  public enum Sign
  {
    /// <summary>
    /// <para>Indicates that the number is negative.</para>
    /// </summary>
    Negative = -1,
    /// <summary>
    /// <para>Indicates that the number is zero.</para>
    /// </summary>
    Zero = 0,
    /// <summary>
    /// <para>Indicates that the number is positive.</para>
    /// </summary>
    Positive = 1
  }
}
