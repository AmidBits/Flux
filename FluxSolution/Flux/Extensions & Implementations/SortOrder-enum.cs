namespace Flux
{
  /// <summary>
  /// <para>Specifies the order for sorting operations.</para>
  /// </summary>
  public enum SortOrder
  {
    /// <summary>
    /// <para>The order is ascending, i.e. going from low-to-high or first-to-last.</para>
    /// </summary>
    Ascending = 1,
    /// <summary>
    /// <para>The order is descending, i.e. going from high-to-low or last-to-first.</para>
    /// </summary>
    Descending = 2
  }
}
